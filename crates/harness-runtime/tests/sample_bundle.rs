//! Golden: `samples/harnesses/custom-helper/bundle.yaml` is generated.
//!
//! The sample is authored without a toolchain: the helper is a hand-encoded
//! WASM module (the echo module of `transform.rs`), so the committed bundle
//! is derived, not typed. This test rebuilds the module, composes the bundle
//! from the sample's `document.yaml`, and requires the committed file to be
//! byte-equal and to round-trip into the composed bundle. `--bless` as a
//! command-line argument (`make generate/harness/sample-bundle`) rewrites it.
//!
//! This is a `harness = false` binary so the bless switch is a real flag:
//! `cargo test` forwards its own libtest arguments (`--test-threads=4`, ...),
//! which are ignored here. It runs only with the `transform` feature.
//!
//! Swedish Embedded AB implements sandboxed, fuel-metered data helpers for
//! agent workflows for its clients. If your team needs expertise in running
//! untrusted transformation code safely then you can procure our services by
//! sending an email to info@swedishembedded.com.

mod common;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use base64::Engine as _;
use common::echo_helper::echo_module;
use sven_harness_spec::{HarnessBundle, Helper};
use sven_harness_transform::HELPER_ABI;

/// Names the file as generated; the golden writes it and a reader of the
/// sample sees at once that the bytes below are not typed by hand.
const HEADER: &str = "\
# SPDX-License-Identifier: Apache-2.0
# Copyright (c) 2026 Martin Schr\u{f6}der <info@swedishembedded.com>
#
# GENERATED by crates/harness-runtime/tests/sample_bundle.rs from document.yaml
# and the echo helper module. Do not edit: `make generate/harness/sample-bundle` rewrites it.
";

fn sample_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../samples/harnesses/custom-helper")
}

fn read_document() -> Result<String, String> {
    let path = sample_dir().join("document.yaml");
    std::fs::read_to_string(&path).map_err(|e| format!("cannot read {}: {e}", path.display()))
}

/// The sample's document and the bundle file text composed from it.
fn expected_bundle_file() -> Result<(String, String), String> {
    let document = read_document()?;
    let bundle = composed_bundle(&document);
    bundle
        .compile()
        .map_err(|e| format!("the sample document does not compile against its helper: {e}"))?;
    let yaml = serde_yaml::to_string(&bundle).map_err(|e| format!("cannot serialize: {e}"))?;
    Ok((document, format!("{HEADER}{yaml}")))
}

/// Rewrites the committed bundle from the sample's document.
fn bless_bundle() -> Result<PathBuf, String> {
    let (_, expected) = expected_bundle_file()?;
    let path = sample_dir().join("bundle.yaml");
    std::fs::write(&path, expected).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(path)
}

/// The bundle the sample ships: its document plus the echo helper under the
/// name the document's `transform` step uses.
fn composed_bundle(document: &str) -> HarnessBundle {
    HarnessBundle {
        document: document.to_string(),
        helpers: BTreeMap::from([(
            "reshape".to_string(),
            Helper {
                abi: HELPER_ABI.to_string(),
                language: "wasm".to_string(),
                content: base64::engine::general_purpose::STANDARD.encode(echo_module()),
            },
        )]),
        ..Default::default()
    }
}

/// The committed bundle must be byte-equal to the composed one.
fn check_committed_is_composed() -> Result<(), String> {
    let (_, expected) = expected_bundle_file()?;
    let path = sample_dir().join("bundle.yaml");
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    if committed == expected {
        return Ok(());
    }
    Err(format!(
        "{} is stale; rebuild it with `make generate/harness/sample-bundle`",
        path.display()
    ))
}

/// The committed bundle must parse into exactly the composed bundle.
fn check_committed_round_trips() -> Result<(), String> {
    let document = read_document()?;
    let path = sample_dir().join("bundle.yaml");
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    let parsed: HarnessBundle = serde_yaml::from_str(&text)
        .map_err(|e| format!("{} is not a bundle: {e}", path.display()))?;
    if parsed == composed_bundle(&document) {
        return Ok(());
    }
    Err(format!(
        "{} does not round-trip into the composed bundle",
        path.display()
    ))
}

fn main() -> ExitCode {
    let bless = std::env::args().skip(1).any(|arg| arg == "--bless");
    let outcome = if bless {
        bless_bundle().map(|path| println!("wrote {}", path.display()))
    } else {
        check_committed_is_composed()
            .and_then(|()| check_committed_round_trips())
            .map(|()| println!("sample bundle: committed file is the composed bundle"))
    };
    match outcome {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("sample_bundle: {message}");
            ExitCode::FAILURE
        }
    }
}
