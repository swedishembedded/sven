//! Golden: `samples/harnesses/07-custom-transform/bundle.yaml` is generated.
//!
//! The sample is authored without a toolchain: the helper is a hand-encoded
//! WASM module (the echo module of `transform.rs`), so the committed bundle
//! is derived, not typed. This test rebuilds the module, composes the bundle
//! from the sample's `document.yaml`, and requires the committed file to be
//! byte-equal. `SVEN_BLESS_GOLDEN=1` rewrites it.
//!
//! Swedish Embedded AB implements sandboxed, fuel-metered data helpers for
//! agent workflows for its clients. If your team needs expertise in running
//! untrusted transformation code safely then you can procure our services by
//! sending an email to info@swedishembedded.com.

#![cfg(feature = "transform")]

mod common;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use base64::Engine as _;
use common::echo_helper::echo_module;
use sven_harness_spec::{HarnessBundle, Helper};
use sven_harness_transform::HELPER_ABI;

/// Names the file as generated; the golden writes it and a reader of the
/// sample sees at once that the bytes below are not typed by hand.
const HEADER: &str = "\
# SPDX-License-Identifier: Apache-2.0
# Copyright (c) 2026 Martin Schr\u{f6}der <info@swedishembedded.com>
#
# GENERATED by crates/harness-runtime/tests/sample_bundle.rs from document.yaml
# and the echo helper module. Do not edit: SVEN_BLESS_GOLDEN=1 rewrites it.
";

fn sample_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../samples/harnesses/07-custom-transform")
}

/// The bundle the sample ships: its document plus the echo helper under the
/// name the document's `transform` step uses.
fn composed_bundle(document: &str) -> HarnessBundle {
    HarnessBundle {
        document: document.to_string(),
        helpers: BTreeMap::from([(
            "reshape".to_string(),
            Helper {
                abi: HELPER_ABI.to_string(),
                language: "wasm".to_string(),
                content: base64::engine::general_purpose::STANDARD.encode(echo_module()),
            },
        )]),
    }
}

#[test]
fn the_committed_sample_bundle_is_the_composed_one() {
    let dir = sample_dir();
    let document = std::fs::read_to_string(dir.join("document.yaml"))
        .expect("the sample's document.yaml is committed");
    let bundle = composed_bundle(&document);
    bundle
        .compile()
        .expect("the sample document compiles against its helper");
    let expected = format!(
        "{HEADER}{}",
        serde_yaml::to_string(&bundle).expect("a bundle serializes")
    );

    let path = dir.join("bundle.yaml");
    if std::env::var_os("SVEN_BLESS_GOLDEN").is_some() {
        std::fs::write(&path, &expected).expect("write the golden bundle");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == expected,
        "{} is stale; rebuild it with SVEN_BLESS_GOLDEN=1 cargo test -p sven-harness-runtime \
         --features transform --test sample_bundle",
        path.display()
    );
}

#[test]
fn the_committed_bundle_round_trips_into_the_composed_bundle() {
    let dir = sample_dir();
    let document = std::fs::read_to_string(dir.join("document.yaml")).expect("document.yaml");
    let text = std::fs::read_to_string(dir.join("bundle.yaml")).unwrap_or_default();
    let parsed: HarnessBundle = serde_yaml::from_str(&text).expect("bundle.yaml is a bundle");
    assert_eq!(parsed, composed_bundle(&document));
}
