# The Makefile's public targets form a tree that `make <TAB>` reveals one
# level at a time: `test`, then `test/`, then `test/harness`. That only works
# while the names keep to a convention, so this gate enforces it.
#
#   1. A public name is lowercase `[a-z0-9-]` segments joined by `/`.
#   2. Every proper prefix of a public name is itself a defined target, so tab
#      completion can descend through every level.
#   3. Every public name has a `## name - description` doc line in the
#      Makefile (`make help` is built from those lines). `<x>` in a doc name
#      stands for one path segment, for generated targets such as
#      `papers/<name>/pdf`. Conversely a doc line without a target is stale.
#
# "Public" means a static .PHONY target whose name starts with neither `_` nor
# `.`. Pattern rules (`samples/%/build`) and file targets are not checked; the
# list is read from `make -pRrq`, so targets generated by $(wildcard) count.
#
# Usage: scripts/gates/check-make-targets.sh
set -euo pipefail

cd "$(dirname "$0")/../.."
export LC_ALL=C

# -q never runs a recipe; `.DEFAULT` is a goal no rule names, the same trick
# bash-completion uses to get the database without building anything.
db=$("${MAKE:-make}" -pRrq .DEFAULT 2>/dev/null || true)

# Defined rule targets (T) and .PHONY names (P), one per line.
defined=$(awk '/^[^#[:space:].%][^:=%]*:([^=]|$)/ { sub(/:.*/, ""); print }' <<<"$db" | sort -u)
phony=$(awk '/^\.PHONY:/ { for (i = 2; i <= NF; i++) print $i }' <<<"$db" | sort -u)
public=$(comm -12 <(printf '%s\n' "$defined") <(printf '%s\n' "$phony") | grep -Ev '^[_.]|%' || true)

# Doc names, with <x> turned into a one-segment regex.
docs=$(sed -nE 's/^## ([^ ]+) - .*/\1/p' Makefile)

failures=0
fail() {
    printf 'check-make-targets: %s: %s\n' "$1" "$2" >&2
    failures=$((failures + 1))
}

while IFS= read -r name; do
    [ -n "$name" ] || continue

    if ! [[ $name =~ ^[a-z0-9-]+(/[a-z0-9-]+)*$ ]]; then
        fail "$name" "not lowercase [a-z0-9-] segments separated by '/'"
    fi

    prefix=$name
    while [[ $prefix == */* ]]; do
        prefix=${prefix%/*}
        if ! grep -qxF -- "$prefix" <<<"$defined"; then
            fail "$name" "prefix '$prefix' is not a defined target (tab completion cannot descend)"
        fi
    done

    documented=0
    while IFS= read -r doc; do
        [ -n "$doc" ] || continue
        pattern=$(sed -E 's/<[^>]+>/[^\/]+/g' <<<"$doc")
        if [[ $name =~ ^${pattern}$ ]]; then
            documented=1
            break
        fi
    done <<<"$docs"
    [ "$documented" = 1 ] || fail "$name" "no '## $name - description' line in Makefile"
done <<<"$public"

while IFS= read -r doc; do
    [ -n "$doc" ] || continue
    [[ $doc == *"<"* ]] && continue
    grep -qxF -- "$doc" <<<"$defined" || fail "$doc" "documented in Makefile but no such target"
done <<<"$docs"

if [ "$failures" -ne 0 ]; then
    printf 'check-make-targets: %d violation(s); see the convention at the top of this script\n' "$failures" >&2
    exit 1
fi
printf 'check-make-targets: %d public targets, all named, reachable and documented\n' \
    "$(grep -c . <<<"$public")"
