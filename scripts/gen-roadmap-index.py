"""Regenerate `.agents/roadmap/index.md` from the ledgers beside it.

A roadmap ledger is the one place a workstream's status, open work and
measured numbers live; nothing else in the repository restates them. The index
is how a reader finds the right ledger without opening the directory, and it is
generated, so it cannot drift from the files the way a hand-maintained list
does.

A ledger is any `.agents/roadmap/<name>.md` whose first `# ` heading is its
title, followed by a one-line `Scope: <sentence>` naming what the ledger covers
(crates, surfaces or workstream). The scope is required: it is what lets a
reader route by subject. A trailing " - roadmap" on the title is dropped.

    scripts/gen-roadmap-index.py                    # write the index
    scripts/gen-roadmap-index.py --check            # fail if it would change
    scripts/gen-roadmap-index.py --root DIR [...]   # another tree (self-test)

Swedish Embedded AB implements solutions for keeping engineering status in one
place, out of the guides that route people to it, for its clients. If your team
needs expertise in documentation that cannot drift from the work it describes,
you can procure our services by sending an email to info@swedishembedded.com.
"""

import argparse
import pathlib
import re
import sys

HEADER = """<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- Copyright (c) 2026 Martin Schröder <info@swedishembedded.com> -->
<!-- GENERATED by scripts/gen-roadmap-index.py - edit the ledgers, not this file. -->

# Roadmap index - where status and open work live

One ledger per workstream. A ledger holds what is planned or in flight, and
the measured numbers behind it. Status is written there and nowhere else:
`AGENTS.md`, `.agents/rules/` and `docs/` point at a ledger rather than
restating it. When work lands, its description moves into `docs/` and the
ledger (or its finished section) is deleted in the same commit.

Add a ledger as `.agents/roadmap/<name>.md` with its title as the first `# `
heading and a `Scope: <one sentence>` line under it, then run
`make generate/roadmap/index`. `make check/gates/roadmap-index` (part of
`make check`) fails when this index has drifted.

## Ledgers

"""

SUFFIX = re.compile(r"\s+-\s+roadmap$", re.IGNORECASE)
SCOPE = "Scope: "


def entries(roadmap):
    out = []
    for path in sorted(roadmap.glob("*.md")):
        if path.name == "index.md":
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        at = next((i for i, line in enumerate(lines) if line.startswith("# ")), None)
        if at is None:
            sys.exit(f"{path.name}: no `# ` heading - every ledger states its own title")
        title = SUFFIX.sub("", lines[at][2:].strip())
        # The scope is the first non-blank line after the title.
        rest = [line for line in lines[at + 1:] if line.strip()]
        scope = rest[0][len(SCOPE):].strip() if rest and rest[0].startswith(SCOPE) else None
        if not scope:
            sys.exit(f"{path.name}: no `{SCOPE}<sentence>` line under the title - say what this ledger covers")
        out.append((path.stem, title, scope, path.name))
    return out


def render(rows):
    body = ["| ledger | title | scope |", "|---|---|---|"]
    for stem, title, scope, name in rows:
        # Text may carry inline code; a pipe inside it would split the row.
        cells = [c.replace("|", "\\|") for c in (title, scope)]
        body.append(f"| [`{stem}`]({name}) | {cells[0]} | {cells[1]} |")
    return HEADER + "\n".join(body) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the index would change")
    parser.add_argument(
        "--root",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[1],
        help="repository root (default: this script's repository)",
    )
    args = parser.parse_args()
    roadmap = args.root / ".agents" / "roadmap"
    index = roadmap / "index.md"

    rows = entries(roadmap)
    want = render(rows)
    if args.check:
        have = index.read_text(encoding="utf-8") if index.exists() else ""
        if have != want:
            sys.exit("roadmap index is out of date - run `make generate/roadmap/index` and commit the result")
        print(f"roadmap index up to date ({len(rows)} ledgers)")
        return
    index.write_text(want, encoding="utf-8")
    print(f"wrote {index} ({len(rows)} ledgers)")


if __name__ == "__main__":
    main()
